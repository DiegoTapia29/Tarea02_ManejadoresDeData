from collections import deque

class Solution:
    def maxSlidingWindow(self, nums: list[int], k: int) -> list[int]:
        cola = deque()
        resultado = []

        for i, num in enumerate(nums):
            # Eliminar índices que ya no están en la ventana actual
            while cola and cola[0] < i - k + 1:
                cola.popleft()

            # Mantener la cola monótona decreciente
            while cola and nums[cola[-1]] < num:
                cola.pop()

            cola.append(i)

            # Agregar el máximo a la respuesta cuando la ventana alcanza tamaño k
            if i >= k - 1:
                resultado.append(nums[cola[0]])

        return resultado