import re

class Solution:
    def isNumber(self, s: str) -> bool:
        # Patrón:
        # [+-]? : Signo opcional
        # ((\d+\.?\d*)|(\.\d+)) : Entero con punto opcional y decimales, o solo punto y decimales
        # ([eE][+-]?\d+)? : Exponente opcional (e o E, signo opcional, entero)
        patron = r'[+-]?((\d+\.?\d*)|(\.\d+))([eE][+-]?\d+)?'
        return bool(re.fullmatch(patron, s))