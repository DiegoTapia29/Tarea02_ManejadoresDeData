import re

class Solution:
    def numUniqueEmails(self, emails: list[str]) -> int:
        unicos = set()
        for email in emails:
            local, dominio = email.split('@')
            local = re.sub(r'\+.*', '', local)
            local = re.sub(r'\.', '', local)
            unicos.add(f"{local}@{dominio}")
        return len(unicos)