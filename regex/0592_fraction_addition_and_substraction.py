import re
import math

class Solution:
    def fractionAddition(self, expression: str) -> str:
        fracciones = re.findall(r'[+-]?\d+/\d+', expression)
        num_res, den_res = 0, 1

        for frac in fracciones:
            n, d = map(int, frac.split('/'))
            num_res = num_res * d + n * den_res
            den_res *= d
            gcd = math.gcd(abs(num_res), den_res)
            num_res //= gcd
            den_res //= gcd

        return f"{num_res}/{den_res}"