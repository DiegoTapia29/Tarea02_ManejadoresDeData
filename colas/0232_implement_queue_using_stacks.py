class MyQueue:
    def __init__(self):
        self.entrada = []
        self.salida = []

    def push(self, x: int) -> None:
        self.entrada.append(x)

    def _transferir(self):
        if not self.salida:
            while self.entrada:
                self.salida.append(self.entrada.pop())

    def pop(self) -> int:
        self._transferir()
        return self.salida.pop()

    def peek(self) -> int:
        self._transferir()
        return self.salida[-1]

    def empty(self) -> bool:
        return not self.entrada and not self.salida